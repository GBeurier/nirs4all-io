@pytest.mark.parametrize("vector", VECTORS["precision_vectors"], ids=lambda v: f"{v['source_dtype']}-{v['requested_dtype']}-{v['consumer']}-k{v['target_kind']}")
def test_precision_vectors(vector: dict) -> None:
    request = None if vector["requested_dtype"] is None else _DTYPES.get(vector["requested_dtype"], "unknown-tag")
    if vector["target_kind"] == 2:
        # string-label targets never accept a numeric precision request
        assert "refusal" in vector["result"]
        block = _target_assembled(string_labels=True)
        with pytest.raises(NumericContractError):
            DatasetPackage.from_assembled(block, targets="float32")
        return
    try:
        record = PrecisionRecord.select(vector["source_dtype"], request, vector["consumer"], feature=True)
    except NumericContractError:
        assert "refusal" in vector["result"]
        return
    expected = vector["result"]["value"]
    assert record.to_dict() == {
        "dtype": _DTYPES[expected["dtype"]],
        "origin": _ORIGINS[expected["origin"]],
        "source_dtype": expected["source_dtype"],
        "requested_dtype": None if expected["requested_dtype"] is None else _DTYPES[expected["requested_dtype"]],
        "consumer": expected["consumer"],
    }


def _target_assembled(*, string_labels: bool) -> AssembledDataset:
    assembled = AssembledDataset(name="t", task_type="multiclass", signal_type="auto", n_sources=1)
    block = PartitionBlock(n_samples=2, source_ids=["X"], X=[np.zeros((2, 1))], feature_headers=[["0"]], header_units=["index"], signal_types=[None])
    block.y = np.array([[0.0], [1.0]])
    block.y_headers = ["y"]
    block.y_categorical = {"y": {"categories": ["a", "b"]}} if string_labels else {}
    assembled.blocks["train"] = block
    return assembled


# --------------------------------------------------------------------------- #
# Block frames, tabular missingness, dtype framing                             #
# --------------------------------------------------------------------------- #
def _exact(spec: dict, precision: dict) -> ExactBlock:
    record = PrecisionRecord(
        _DTYPES[precision["dtype"]], _ORIGINS[precision["origin"]], precision["source_dtype"], None if precision["requested_dtype"] is None else _DTYPES[precision["requested_dtype"]], precision["consumer"]
    )
    mask = np.array(spec["mask"], dtype=bool).reshape(spec["rows"], spec["cols"])
    if spec["dtype"] == 3:
        values = np.empty(mask.shape, dtype=object)
        values.ravel()[:] = [v if m else "" for v, m in zip(spec["values"], spec["mask"], strict=True)]
        return ExactBlock(record, values, mask)
    width = 4 if spec["dtype"] == 1 else 8
    raw = b"".join((int(v, 16) if m else 0).to_bytes(width, "little") for v, m in zip(spec["values"], spec["mask"], strict=True))
    values = np.frombuffer(raw, dtype="<f4" if width == 4 else "<f8").astype(_DTYPES[spec["dtype"]]).reshape(mask.shape)
    return ExactBlock(record, values, mask)


@pytest.mark.parametrize("vector", VECTORS["dtype_framing"], ids=lambda v: v["name"])
def test_dtype_framing_vectors(vector: dict) -> None:
    dtype = "float32" if vector["name"].endswith("f32") else "float64"
    block = ExactBlock(PrecisionRecord(dtype), np.zeros((1, 1), dtype), np.ones((1, 1), bool))
    assert block.to_bytes().hex() == vector["preimage_hex"]
    assert hashlib.sha256(block.to_bytes()).hexdigest() == vector["sha256"]
    assert VECTORS["dtype_framing"][0]["sha256"] != VECTORS["dtype_framing"][1]["sha256"]


@pytest.mark.parametrize("vector", VECTORS["tabular_missingness"], ids=lambda v: v["name"])
def test_tabular_missingness_vectors(vector: dict) -> None:
    cell = np.array([[_f64(vector["input"]["input_ieee_f64_hex"])]])
    block = ExactBlock.from_matrix(cell, source_dtype=None, request=None, consumer=None, feature=False)
    assert block.to_bytes().hex() == vector["preimage_hex"]
    assert hashlib.sha256(block.to_bytes()).hexdigest() == vector["sha256"]
    normalized = vector["input"]["normalized_block"]
    assert block.validity.ravel().tolist() == normalized["mask"]


def test_tabular_infinity_refuses() -> None:
    with pytest.raises(NumericContractError):
        ExactBlock.from_matrix(np.array([[np.inf]]), source_dtype=None, request=None, consumer=None, feature=True)


def test_every_nan_payload_normalizes_to_one_missing_cell() -> None:
    a = ExactBlock.from_matrix(np.array([[_f64("7ff8000000000001")]]), source_dtype=None, request=None, consumer=None, feature=True)
    b = ExactBlock.from_matrix(np.array([[_f64("fff8000000000002")]]), source_dtype=None, request=None, consumer=None, feature=True)
    assert a.to_bytes() == b.to_bytes()
    assert a.values.tobytes() == b"\x00" * 8


# --------------------------------------------------------------------------- #
# Package payload framing (H4)                                                 #
# --------------------------------------------------------------------------- #
def _feature_payload(spec: dict) -> FeatureMatrix:
    axes = [
        {
            "name": a["name"],
            "unit": a["unit"],
            "coordinates": None
            if a["coordinates"] is None
            else [_f64(x) for x in a["coordinates"]["values"]]
            if a["coordinates"]["kind"] == 1
            else list(a["coordinates"]["values"]),
        }
        for a in spec["axes"]
    ]
    return FeatureMatrix(
        matrix=_exact(spec["block"], spec["precision"]),
        headers=list(spec["names"]),
        header_unit="",
        signal_type=None,
        source_id=spec["source_id"],
        representation_id=spec["representation_id"],
        feature_names=None if spec["names"] is None else list(spec["names"]),
        axes=axes,
    )


def _target_payload(spec: dict) -> TargetColumn:
    return TargetColumn(spec["name"], _KINDS[spec["kind"]], _exact(spec["block"], spec["precision"]))


def test_package_payload_vectors() -> None:
    by_name = {v["name"]: v for v in VECTORS["package_vectors"]}
    feature = by_name["feature_payload_v4"]
    assert _feature_content_bytes(_feature_payload(feature["input"])).hex() == feature["preimage_hex"]
    target = by_name["target_payload_v4"]
    table = TargetTable(columns=[_target_payload(t) for t in target["input"]])
    assert _target_content_bytes(table).hex() == target["preimage_hex"]
    weights = by_name["weights_payload_v4"]
    block = _exact({"dtype": 2, "rows": 2, "cols": 1, "values": ["3ff0000000000000", "4000000000000000"], "mask": [True, True]}, {"dtype": 2, "origin": 0, "source_dtype": None, "requested_dtype": None, "consumer": None})
    assert _weights_content_bytes(WeightsVector(matrix=block)).hex() == weights["preimage_hex"]
    for vector in by_name.values():
        assert hashlib.sha256(bytes.fromhex(vector["preimage_hex"])).hexdigest() == vector["sha256"]


# --------------------------------------------------------------------------- #
# Base-cohort projection preimages                                             #
# --------------------------------------------------------------------------- #
def _package_from_cohort(cohort: dict) -> DatasetPackage:
    """Build the oracle package a vector cohort denotes (rows grouped by contiguous partition)."""
    rows = cohort["rows"]
    groups: list[tuple[str, list[int]]] = []
    for index, row in enumerate(rows):
        if groups and groups[-1][0] == row["partition"]:
            groups[-1][1].append(index)
        else:
            groups.append((row["partition"], [index]))
    assert len({name for name, _ in groups}) == len(groups)
    assembled = AssembledDataset(name="vector", task_type="regression", signal_type="auto", n_sources=len(cohort["features"]))
    assembled.identity = {"source_ids": [], "sample_id": "sample_id", "observation_id": "observation_id", "repetition_id": None, "group_id": "group_id"}
    assembled.fold_provenance = [{"train_observation_ids": f["train"], "validation_observation_ids": f["validation"]} for f in (cohort["folds"] or [])]
    if cohort["fold_assignments"] is not None:
        assembled.audits.append({"raw_fold_assignments": cohort["fold_assignments"], "input_sample_ids": [r["sample_id"] for r in rows]})
    for name, indexes in groups:
        block = PartitionBlock(n_samples=len(indexes))
        frame = {
            "sample_id": [rows[i]["sample_id"] for i in indexes],
            "observation_id": [rows[i]["observation_id"] for i in indexes],
            "group_id": [rows[i]["group_id"] for i in indexes],
            "origin_id": [rows[i]["origin_id"] for i in indexes],
        }
        block.metadata = pd.DataFrame(frame)
        assembled.blocks[name] = block
    package = DatasetPackage.from_assembled(assembled)
    partitions = {}
    for name, indexes in groups:
        payloads: list[tuple[str, Any]] = []
        for k, spec in enumerate(cohort["features"]):
            whole = _feature_payload(spec)
            sliced = ExactBlock(whole.matrix.precision, whole.matrix.values[indexes], whole.matrix.validity[indexes])
            payloads.append((f"{name}/x{k}", FeatureMatrix(sliced, whole.headers, "nm", None, whole.source_id, whole.representation_id, whole.feature_names, whole.axes)))
        if cohort["targets"] is not None:
            columns, categorical = [], {}
            for spec in cohort["targets"]:
                column = _target_payload(spec)
                columns.append(TargetColumn(column.name, column.kind, ExactBlock(column.block.precision, column.block.values[indexes], column.block.validity[indexes])))
                if column.kind == "classification_string":
                    categorical[column.name] = {"categories": ["one", "two"], "source_dtype": column.block.precision.source_dtype}
            payloads.append((f"{name}/y", TargetTable(columns=columns, categorical=categorical)))
        payloads.append((f"{name}/metadata", package.partitions[name].payloads[-1][1]))
        partitions[name] = type(package.partitions[name])(n_samples=len(indexes), payloads=payloads, source_ids=[f["source_id"] for f in cohort["features"]])
    return DatasetPackage(**{**package.__dict__, "partitions": partitions})


# Present-but-empty fold / target lists have no IR representation (an empty list IS
# absent in the assembled model); the reviewed byte vectors for them are covered
# by the strict encoder pairs below instead.
_IR_UNREPRESENTABLE = {"folds_present_empty", "present_empty_targets"}


@pytest.mark.parametrize("vector", [v for v in VECTORS["projection_vectors"] if v["name"] not in _IR_UNREPRESENTABLE], ids=lambda v: v["name"])
def test_projection_vectors(vector: dict) -> None:
    package = _package_from_cohort(vector["input"])
    projection = package.executed_projection([vector["input"]["features"][0]["source_id"]])
    assert projection.feature_preimage.hex() == vector["features"]["preimage_hex"]
    assert projection.target_preimage.hex() == vector["targets"]["preimage_hex"]
    assert projection.identity.feature_content_fingerprint == vector["features"]["sha256"]
    assert projection.identity.target_content_fingerprint == vector["targets"]["sha256"]


def test_projection_comparisons() -> None:
    digests = {}
    for vector in VECTORS["projection_vectors"]:
        if vector["name"] in _IR_UNREPRESENTABLE:
            continue
        result = _package_from_cohort(vector["input"]).executed_projection([vector["input"]["features"][0]["source_id"]]).identity
        digests[vector["name"]] = {"features": result.feature_content_fingerprint, "targets": result.target_content_fingerprint}
    checked = 0
    for comparison in VECTORS["comparisons"]:
        if comparison["left"] in digests and comparison["right"] in digests:
            equal = digests[comparison["left"]][comparison["side"]] == digests[comparison["right"]][comparison["side"]]
            assert equal == comparison["equal"], comparison
            checked += 1
    assert checked == len(VECTORS["comparisons"]) - 2  # the two IR-unrepresentable pairs


def test_unrepresentable_vectors_stay_distinct_in_the_reviewed_vectors() -> None:
    by_name = {v["name"]: v for v in VECTORS["projection_vectors"]}
    for left, right in (("folds_absent", "folds_present_empty"), ("absent_targets", "present_empty_targets")):
        side = "features" if left.startswith("folds") else "targets"
        assert by_name[left][side]["sha256"] != by_name[right][side]["sha256"]


def test_requested_f32_vector_is_reproduced_by_owner_quantization() -> None:
    """The requested-F32 block is what the owner produces from the F64 inputs, once."""
    base = next(v for v in VECTORS["projection_vectors"] if v["name"] == "base")["input"]["features"][0]["block"]
    source = np.array([_f64(x) for x in base["values"]]).reshape(2, 2)
    block = ExactBlock.from_matrix(source, source_dtype="float64", request="float32", consumer=None, feature=True)
    requested = next(v for v in VECTORS["projection_vectors"] if v["name"] == "requested_f32")["input"]["features"][0]
    assert block.precision.to_dict() == {"dtype": "float32", "origin": "requested", "source_dtype": "float64", "requested_dtype": "float32", "consumer": None}
    assert block.to_bytes() == _exact(requested["block"], requested["precision"]).to_bytes()
    assert block.values[0, 0] == block.values[0, 1]  # the F64 ULP collapsed, honestly recorded
