def test_primitive_literals() -> None:
    actual = {
        "u32_version_one": (1).to_bytes(4, "little"),
        "mask_false_true": bytes([False, True]),
        "u64_258": u64(258),
        "empty_bytes": blob(b""),
        "utf8_e_acute": string("é"),
        "decomposed_e_acute": string("é"),
        "embedded_separator": string("a\x1fb"),
        "absent_string": option_string(None),
        "present_empty_string": option_string(""),
        "empty_string_list": strings([]),
        "one_empty_string": strings([""]),
        "default_f64_precision": PrecisionRecord().to_bytes(),
        "f32_positive_zero_1x1": ExactBlock(
            PrecisionRecord("float32"), np.zeros((1, 1), np.float32), np.ones((1, 1), bool)
        ).to_bytes(),
    }
    for vector in VECTORS["primitives"]:
        assert actual[vector["name"]].hex() == vector["input"]["literal_expected_hex"] == vector["preimage_hex"], vector["name"]
        assert hashlib.sha256(actual[vector["name"]]).hexdigest() == vector["sha256"]
    assert {v["name"] for v in VECTORS["primitives"]} == set(actual)


def test_surrogate_strings_refuse() -> None:
    with pytest.raises(NumericContractError):
        string("\ud800")


@pytest.mark.parametrize("vector", VECTORS["conversion_vectors"], ids=lambda v: v["name"])
def test_conversion_vectors(vector: dict) -> None:
    source = np.array([_f64(vector["input_ieee_f64_hex"])])
    if "refusal" in vector["result"]:
        with pytest.raises(NumericContractError):
            round_storage(source, "float32")
        return
    rounded = round_storage(source, "float32")
    assert rounded.dtype == np.float32
    assert _hex32(rounded[0]) == vector["expected"] == vector["result"]["value"]
    block = ExactBlock.from_matrix(source.reshape(1, 1), source_dtype=None, request="float32", consumer=None, feature=True)
    assert hashlib.sha256(PrecisionRecord().to_bytes()).hexdigest()  # P is not part of the output block
    assert block.to_bytes().hex() == vector["output_block"]["preimage_hex"]
    assert hashlib.sha256(block.to_bytes()).hexdigest() == vector["output_block"]["sha256"]


def test_f32_integer_domain_decoding_is_exact() -> None:
    validate_label(16777218, "float32")
    with pytest.raises(NumericContractError):
        validate_label(16777217, "float32")


@pytest.mark.parametrize("vector", VECTORS["label_vectors"], ids=lambda v: f"{v['integer_decimal']}-{_DTYPES[v['dtype']]}")
def test_label_vectors(vector: dict) -> None:
    label, dtype = int(vector["integer_decimal"]), _DTYPES[vector["dtype"]]
    try:
        validate_label(label, dtype)
        block = ExactBlock.from_matrix(np.array([[float(label)]]), source_dtype=None, request=dtype, consumer=None, feature=False)
    except NumericContractError:
        assert "refusal" in vector["result"], vector
        return
    assert vector["result"]["value"] == block.values.astype(">f4" if dtype == "float32" else ">f8").tobytes().hex()


