"""Conformance of the Python oracle to the reviewed Float64 DESIGN vectors.

``fixtures/float64_design_vectors.json`` is a tracked copy of the reviewed
``design-vectors.json`` (SHA-256 pinned below). The vectors were produced by an
independent stdlib reference; this oracle implements the normative bytes on its
own and is checked against them. Nothing here executes Rust, and no expected
value is generated by the code under test.
"""

