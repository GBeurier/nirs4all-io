_PATH = Path(__file__).parent / "fixtures" / "float64_design_vectors.json"
_PINNED_SHA256 = "b62cad5ac4f682fc48f2b3fbeb2bc9b37b6b3745acfb5a65f2863a51dceffb8b"
VECTORS = json.loads(_PATH.read_text(encoding="utf-8"))
_DTYPES = {1: "float32", 2: "float64", 3: "string-label"}
_ORIGINS = {0: "default", 1: "source-declared", 2: "requested", 3: "consumer"}
_KINDS = {0: "numeric", 1: "classification_integer", 2: "classification_string"}


def test_vector_fixture_is_the_reviewed_artifact() -> None:
    assert hashlib.sha256(_PATH.read_bytes()).hexdigest() == _PINNED_SHA256


def _f64(bits: str) -> float:
    return struct.unpack(">d", bytes.fromhex(bits))[0]


def _hex32(value: np.float32) -> str:
    return struct.pack(">f", float(value)).hex()


